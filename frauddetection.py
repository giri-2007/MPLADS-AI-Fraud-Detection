import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import os

def run_complete_mplads_audit(rec_path, sanc_path, comp_path, exp_path, limit_path):
    print("🔄 Step 1: Loading all 5 raw data sheets (Skipping row 1 titles)...")
    try:
        # Load sheets exactly as they are, skipping the title on Row 1
        df_rec = pd.read_excel(rec_path, engine='calamine', skiprows=1)
        df_sanc = pd.read_excel(sanc_path, engine='calamine', skiprows=1)
        df_comp = pd.read_excel(comp_path, engine='calamine', skiprows=1)
        df_exp = pd.read_excel(exp_path, engine='calamine', skiprows=1)
        df_lim = pd.read_excel(limit_path, engine='calamine', skiprows=1)
    except Exception as e:
        print(f"❌ Error loading Excel files: {e}")
        return None

    # Normalize mixed header casing across Excel files before merging.
    for df in [df_rec, df_sanc, df_comp, df_exp, df_lim]:
        rename_map = {}
        for col in df.columns:
            clean = str(col).strip()
            key = clean.lower()

            if key == 'work':
                rename_map[col] = 'WORK'
            elif key == 'constituency':
                rename_map[col] = 'Constituency'
            elif 'member' in key and 'parliament' in key:
                rename_map[col] = 'MP'
            else:
                rename_map[col] = clean

        df.rename(columns=rename_map, inplace=True)

    print("🔀 Step 2: Executing structured cross-lifecycle data merge...")
    # Step A: Merge physical lifecycle using your exact matching keys: 'Constituency' and 'WORK'
    pipeline = pd.merge(df_rec, df_sanc, on=['Constituency', 'WORK'], how='left', suffixes=('_rec', '_sanc'))
    pipeline = pd.merge(pipeline, df_comp, on=['Constituency', 'WORK'], how='left', suffixes=('', '_comp'))
    
    # Step B: Link physical tracking with your transaction records
    merged_data = pd.merge(pipeline, df_exp, on=['Constituency', 'WORK'], how='left', suffixes=('', '_exp'))
    
    # Step C: Inject the macro MP allocation limit constraints using 'Constituency' and 'MP'
    final_df = pd.merge(merged_data, df_lim, on=['Constituency', 'MP'], how='left', suffixes=('', '_lim'))

    print("🛠️ Step 3: Standardizing structural data attributes for computation...")
    # Convert dates using your exact column headers
    for d_col in ['Recommended date', 'Sanction Date', 'Completion Date', 'Expenditure Date']:
        if d_col in final_df.columns:
            final_df[d_col] = pd.to_datetime(final_df[d_col], errors='coerce')
            
    # Convert financial values using your exact column headers
    amt_cols = ['RECOMMENDED AMOUNT', 'Sanction Amount', 'Amount Disbursed', 'Fund Disbursed Amount', 'Allocated AMOUNT']
    for amt_col in amt_cols:
        if amt_col in final_df.columns:
            final_df[amt_col] = pd.to_numeric(final_df[amt_col], errors='coerce').fillna(0)

    print("🚨 Step 4: Cracking core forensic compliance and anomaly algorithms...")

    # --- FORENSIC RULE 1: Ghost Asset Flag ---
    if 'Completion Date' in final_df.columns and 'Image' in final_df.columns:
        final_df['Ghost Asset Flag'] = np.where(
            (final_df['Completion Date'].notna()) & 
            (final_df['Image'].astype(str).str.upper().str.contains('N/A|NA|NONE|0', na=True)), 
            1, 0
        )
    else:
        final_df['Ghost Asset Flag'] = 0

    # --- FORENSIC RULE 2: Split Contracting Flag ---
    if 'Vendor Name' in final_df.columns and 'Expenditure Date' in final_df.columns:
        is_duplicate = final_df.duplicated(subset=['Vendor Name', 'Expenditure Date', 'WORK'], keep=False)
        final_df['Split Contracting Flag'] = np.where((is_duplicate == True) & (final_df['Vendor Name'] != 0), 1, 0)
    else:
        final_df['Split Contracting Flag'] = 0

    # --- FORENSIC RULE 3: Dead-End Expenditure Outflow ---
    if 'Payment Status' in final_df.columns and 'Sanction Amount' in final_df.columns:
        final_df['Dead End Payment Flag'] = np.where(
            (final_df['Payment Status'].astype(str).str.upper().str.contains('SUCCESS|IN-PROGRESS', na=False)) & 
            (final_df['Sanction Amount'] == 0), 
            1, 0
        )
    else:
        final_df['Dead End Payment Flag'] = 0

    # --- FORENSIC RULE 4: MP Fiscal Budget Limit Breach ---
    if 'Sanction Amount' in final_df.columns and 'Allocated AMOUNT' in final_df.columns:
        mp_total_sanctioned = final_df.groupby('MP')['Sanction Amount'].transform('sum')
        final_df['Budget Limit Breach Flag'] = np.where(mp_total_sanctioned > final_df['Allocated AMOUNT'], 1, 0)
    else:
        final_df['Budget Limit Breach Flag'] = 0

    # Clean redundant system structural duplicate columns generated by the merge process
    columns_to_drop = [c for c in final_df.columns if c.endswith('_rec') or c.endswith('_sanc') or c.endswith('_comp') or c.endswith('_exp') or c.endswith('_lim')]
    final_df = final_df.drop(columns=columns_to_drop, errors='ignore')

    # Remove empty columns from final audit output for a cleaner Excel export
    final_df = final_df.dropna(axis=1, how='all')

    return final_df

def generate_visual_charts(df):
    print("📊 Generating constituency red-flag and project comparison charts...")

    flag_cols = [
        'Ghost Asset Flag',
        'Split Contracting Flag',
        'Dead End Payment Flag',
        'Budget Limit Breach Flag'
    ]
    flag_cols = [c for c in flag_cols if c in df.columns]

    if 'Constituency' not in df.columns or not flag_cols:
        metrics = {
            'Ghost Assets': df['Ghost Asset Flag'].sum() if 'Ghost Asset Flag' in df.columns else 0,
            'Split Contracts': df['Split Contracting Flag'].sum() if 'Split Contracting Flag' in df.columns else 0,
            'Dead-End Leakage': df['Dead End Payment Flag'].sum() if 'Dead End Payment Flag' in df.columns else 0,
            'MP Limit Breaches': df['Budget Limit Breach Flag'].sum() if 'Budget Limit Breach Flag' in df.columns else 0
        }
        plt.figure(figsize=(10, 5))
        colors = ['#e74c3c', '#e67e22', '#c0392b', '#9b59b6']
        bars = plt.bar(metrics.keys(), metrics.values(), color=colors, edgecolor='black', width=0.5)
        for bar in bars:
            yval = bar.get_height()
            plt.text(bar.get_x() + bar.get_width()/2.0, yval + 0.1, int(yval), ha='center', va='bottom', fontweight='bold')
        plt.title('MPLADS Compliance Matrix & Integrity Summary Red Flags', fontsize=12, fontweight='bold', pad=15)
        plt.ylabel('Detected Anomaly Counts', fontsize=10, fontweight='bold')
        plt.grid(axis='y', linestyle='--', alpha=0.5)
        plt.tight_layout()
        chart_image_path = 'mplads_anomaly_chart.png'
        plt.savefig(chart_image_path, dpi=100)
        plt.close()
        return chart_image_path

    constituency_red_flags = df.groupby('Constituency')[flag_cols].sum().sum(axis=1).sort_values(ascending=False)
    top_constituencies = constituency_red_flags.head(10)
    project_counts = df['Constituency'].value_counts().reindex(top_constituencies.index).fillna(0).astype(int)

    overall_comparison = {
        'Total Projects': len(df),
        'Ghost Assets': int(df.get('Ghost Asset Flag', 0).sum()) if 'Ghost Asset Flag' in df.columns else 0,
        'Split Contracting': int(df.get('Split Contracting Flag', 0).sum()) if 'Split Contracting Flag' in df.columns else 0,
    }

    fig, axes = plt.subplots(3, 1, figsize=(14, 12))

    axes[0].bar(top_constituencies.index, top_constituencies.values, color='#d62728', edgecolor='black')
    axes[0].set_title('Number of Red Flags by Constituency', fontsize=12, fontweight='bold')
    axes[0].set_xlabel('Constituency')
    axes[0].set_ylabel('Red Flags Count')
    axes[0].tick_params(axis='x', rotation=45)
    axes[0].grid(axis='y', linestyle='--', alpha=0.5)

    x = range(len(top_constituencies.index))
    axes[1].bar(x, project_counts.values, width=0.35, color='#4e79a7', label='Real Projects')
    axes[1].bar([i + 0.35 for i in x], top_constituencies.values, width=0.35, color='#f28e2b', label='Red Flags')
    axes[1].set_title('Projects vs Red Flags by Constituency', fontsize=12, fontweight='bold')
    axes[1].set_xlabel('Constituency')
    axes[1].set_ylabel('Count')
    axes[1].set_xticks([i + 0.175 for i in x])
    axes[1].set_xticklabels(top_constituencies.index, rotation=45)
    axes[1].legend()
    axes[1].grid(axis='y', linestyle='--', alpha=0.5)

    categories = list(overall_comparison.keys())
    values = list(overall_comparison.values())
    axes[2].bar(categories, values, color=['#4e79a7', '#e15759', '#76b7b2'], edgecolor='black')
    axes[2].set_title('Overall Project vs Red Flag Comparison', fontsize=12, fontweight='bold')
    axes[2].set_ylabel('Count')
    axes[2].tick_params(axis='x', rotation=0)
    axes[2].grid(axis='y', linestyle='--', alpha=0.5)
    for bar, val in zip(axes[2].patches, values):
        axes[2].text(bar.get_x() + bar.get_width()/2, val + 0.5, str(int(val)), ha='center', va='bottom', fontsize=10)

    plt.tight_layout()

    chart_image_path = 'mplads_constituency_redflag_chart.png'
    plt.savefig(chart_image_path, dpi=100)
    plt.close(fig)
    return chart_image_path

